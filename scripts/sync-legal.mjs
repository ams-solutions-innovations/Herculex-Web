// Copies the privacy policy and terms from the Flutter app repo (the single
// source of truth, also shown in-app) into src/content/legal/ as Markdown
// with frontmatter. The copies are committed so Cloudflare builds don't need
// the app repo.
//
//   npm run sync-legal                       # app repo next to this one
//   HERCULEX_APP_DIR=/path/to/Herculex npm run sync-legal

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const appDir = resolve(process.env.HERCULEX_APP_DIR ?? join(root, '..', 'Herculex'));
const outDir = join(root, 'src', 'content', 'legal');

const documents = [
  { slug: 'privacy', source: 'docs/PRIVACY_POLICY.md' },
  { slug: 'terms', source: 'docs/TERMS_OF_SERVICE.md' },
];

/** Pulls `**Label:** value` out of the header block. */
function headerField(lines, label) {
  const prefix = `**${label}:**`;
  const line = lines.find((l) => l.startsWith(prefix));
  return line ? line.slice(prefix.length).trim() : undefined;
}

function toEntry(markdown, source) {
  const lines = markdown.replace(/\r\n/g, '\n').split('\n');
  const titleIndex = lines.findIndex((l) => l.startsWith('# '));
  if (titleIndex === -1) throw new Error(`${source}: no "# " title line`);
  const title = lines[titleIndex].slice(2).replace(/ for Herculex$/, '').trim();

  // The header block runs from the title to the first horizontal rule.
  const ruleIndex = lines.findIndex((l, i) => i > titleIndex && l.trim() === '---');
  if (ruleIndex === -1) throw new Error(`${source}: no "---" after the header block`);
  const header = lines.slice(titleIndex + 1, ruleIndex);
  const lastUpdated = headerField(header, 'Last Updated');
  const publisher = headerField(header, 'Publisher');
  if (!lastUpdated) throw new Error(`${source}: missing **Last Updated:**`);

  // Keep the introduction paragraph(s) but drop the label lines.
  const intro = header.filter((l) => !/^\*\*[A-Za-z ]+:\*\*/.test(l));
  const body = [...intro, ...lines.slice(ruleIndex + 1)].join('\n').trim();

  const frontmatter = [
    '---',
    `title: ${JSON.stringify(title)}`,
    `lastUpdated: ${JSON.stringify(lastUpdated)}`,
    ...(publisher ? [`publisher: ${JSON.stringify(publisher)}`] : []),
    `source: ${JSON.stringify(source)}`,
    '---',
  ].join('\n');

  return `${frontmatter}\n\n<!-- Generated by scripts/sync-legal.mjs from the app repo. Edit ${source} there, not here. -->\n\n${body}\n`;
}

await mkdir(outDir, { recursive: true });
for (const { slug, source } of documents) {
  const markdown = await readFile(join(appDir, source), 'utf8');
  await writeFile(join(outDir, `${slug}.md`), toEntry(markdown, source));
  console.log(`${source} -> src/content/legal/${slug}.md`);
}
